DEFAULT_PROMPT = "你是招聘数据分析助手，回答要简洁、准确，必要时用 Markdown 输出。"


# 已告警过的 scene，避免每次请求都刷日志
_warned: set[str] = set()


def _digest(text: str) -> str:
    """提示词指纹，用于日志定位当次使用的版本。"""
    return hashlib.md5(text.encode("utf-8")).hexdigest()[:8]


def meta(scene: str | None) -> tuple[str, str]:
    """返回 (系统提示词, 日志标识)。

    scene 取值与 Java 侧 SCENES / SCENE_MATCH 一致：jdDesc / skill / jd / chat / match。
    jdDesc 经 SCENE_ALIASES 映射为 jd，提示词与 jd 完全一致，但日志标识仍用原始 scene 便于排查。
    chat 走独立提示词；分析场景由「角色 + 输出规范 + 小节要求」拼装；其余回落默认并告警。
    """
    key = (scene or "").strip().lower()
    base = SCENE_ALIASES.get(key, key)

    if base == "chat":
        return CHAT_PROMPT, f"{key or 'chat'}:{_digest(CHAT_PROMPT)}"

    role = SCENE_ROLES.get(base)
    sections = SCENE_SECTIONS.get(base)
    if role and sections:
        text = f"{role}\n\n{OUTPUT_RULES}\n\n本次需要输出的小节：\n\n{sections}"
        return text, f"{key}:{_digest(text)}"

    if key not in _warned:
        _warned.add(key)
        logger.warning("未配置 scene=%s 的提示词，回落默认", scene)
    return DEFAULT_PROMPT, f"default:{_digest(DEFAULT_PROMPT)}"


def system_prompt(scene: str | None) -> str:
    """只要提示词文本，不需要日志标识时用。"""
    return meta(scene)[0]